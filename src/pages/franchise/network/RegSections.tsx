import type { ReactNode } from 'react'
import { FileDrop, RadioGroup, SectionTitle, SelectField, TextAreaField, TextField } from '@/components/ui/Form'
import { STATES } from '@/data/applications'
import { ENTITY_TYPES, MANAGERS, useNetwork, type EntityType, type ParentKind } from '@/data/network'
import { useFranchises, type Tier } from '@/data/franchises'
import {
  BANK_NAMES, PARENT_KINDS, PARENT_KIND_LABEL, TEAMS, TIER_SHORT, districtsOf, needsGst, parentOptions, requiredDocs,
  type RegErrors, type RegForm,
} from './model'
import { PickField, ReadOnlyField } from './shared'

export type SectionKey = 'basic' | 'entity' | 'business' | 'address' | 'bank' | 'agreement' | 'kyc' | 'mapping'

/** Registration sections of §2.3 — shared by Registration (§2.3) and the Network Profile tab. */
export function RegSections({
  tier, form, set, errors, systemId, frId, entityLocked, parentLocked, onRequestEntityChange, hide = [], disabled, parentLabel,
}: {
  tier: Tier
  form: RegForm
  set: (p: Partial<RegForm>) => void
  errors: RegErrors
  systemId: string
  frId?: string
  entityLocked?: boolean
  parentLocked?: boolean
  onRequestEntityChange?: () => void
  hide?: SectionKey[]
  disabled?: boolean
  parentLabel?: string
}) {
  const net = useNetwork()
  const frs = useFranchises()
  const short = TIER_SHORT[tier]
  const show = (k: SectionKey) => !hide.includes(k)
  const docs = requiredDocs(form.entity)
  const parentOpts = parentOptions(form.parentKind, net.nodes, frs, frId)
  let n = 0
  const num = () => String(++n).padStart(2, '0')

  return (
    <div className="space-y-4">
      {show('basic') && (
        <Section>
          <SectionTitle num={num()} title="Basic Information" sub={`${short} ID is auto-generated by the system.`} />
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            <ReadOnlyField label={`${short} ID (system generated)`} value={systemId} />
            <TextField label="Partner Code" name="partnerCode" required error={errors.partnerCode} value={form.partnerCode} disabled={disabled} onChange={(e) => set({ partnerCode: e.target.value.toUpperCase() })} placeholder="PC-MH-1234" />
            <TextField label="Name (contact person)" name="contactName" required error={errors.contactName} value={form.contactName} disabled={disabled} onChange={(e) => set({ contactName: e.target.value })} />
            <TextField label="Mobile" name="mobile" required inputMode="numeric" maxLength={10} error={errors.mobile} value={form.mobile} disabled={disabled} onChange={(e) => set({ mobile: e.target.value.replace(/\D/g, '') })} placeholder="10-digit mobile" />
            <TextField label="Email" name="email" type="email" required error={errors.email} value={form.email} disabled={disabled} onChange={(e) => set({ email: e.target.value })} />
          </div>
        </Section>
      )}

      {show('entity') && (
        <Section>
          <SectionTitle num={num()} title="Entity Details" sub="The required document checklist changes with the entity type (§3.3, §5)." />
          {entityLocked ? (
            <div className="flex flex-wrap items-end gap-3">
              <div className="w-[260px]"><ReadOnlyField label="Entity type" value={form.entity || '—'} hint="Entity type changes only through an approval request; old details are preserved." /></div>
              {onRequestEntityChange && (
                <button type="button" onClick={onRequestEntityChange} className="mb-5 h-9 rounded-lg border border-slate-200 bg-white px-3.5 text-[12px] font-semibold text-slate-700 hover:bg-slate-50">
                  Request entity change
                </button>
              )}
            </div>
          ) : (
            <RadioGroup<EntityType> label="Entity type *" value={form.entity} onChange={(v) => set({ entity: v })} options={ENTITY_TYPES} error={errors.entity} />
          )}
          {form.entity && (
            <p className="mt-3 text-[12px] text-slate-600">
              Required documents for <b>{form.entity}</b>: {docs.join(', ')}
            </p>
          )}
        </Section>
      )}

      {show('business') && (
        <Section>
          <SectionTitle num={num()} title="Business Details" />
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            <TextField label="Company / Firm / Trade name" name="companyName" required error={errors.companyName} value={form.companyName} disabled={disabled} onChange={(e) => set({ companyName: e.target.value })} />
            <TextField label="PAN" name="pan" required maxLength={10} error={errors.pan} value={form.pan} disabled={disabled} onChange={(e) => set({ pan: e.target.value.toUpperCase() })} placeholder="ABCDE1234F" />
            <TextField label="GST" name="gst" required={needsGst(form.entity)} maxLength={15} error={errors.gst} value={form.gst} disabled={disabled} onChange={(e) => set({ gst: e.target.value.toUpperCase() })} placeholder="27ABCDE1234F1Z5" hint={needsGst(form.entity) ? undefined : 'Optional for this entity'} />
          </div>
        </Section>
      )}

      {show('address') && (
        <Section>
          <SectionTitle num={num()} title="Address Details" />
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            <TextAreaField label="Registered address" name="address" required error={errors.address} value={form.address} disabled={disabled} onChange={(e) => set({ address: e.target.value })} className="sm:col-span-2 lg:col-span-3" />
            <SelectField label="State" name="state" required error={errors.state} options={STATES} value={form.state} disabled={disabled} onChange={(e) => set({ state: e.target.value, district: '' })} />
            <SelectField label="District" name="district" required error={errors.district} options={districtsOf(form.state)} value={form.district} disabled={disabled || !form.state} onChange={(e) => set({ district: e.target.value })} placeholder={form.state ? 'Select' : 'Select state first'} />
            <TextField label="PIN" name="pin" required inputMode="numeric" maxLength={6} error={errors.pin} value={form.pin} disabled={disabled} onChange={(e) => set({ pin: e.target.value.replace(/\D/g, '') })} />
          </div>
        </Section>
      )}

      {show('bank') && (
        <Section>
          <SectionTitle num={num()} title="Bank Details" />
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            <SelectField label="Bank name" name="bankName" required error={errors.bankName} options={BANK_NAMES} value={form.bankName} disabled={disabled} onChange={(e) => set({ bankName: e.target.value })} />
            <TextField label="Account number" name="accountNo" required inputMode="numeric" maxLength={18} error={errors.accountNo} value={form.accountNo} disabled={disabled} onChange={(e) => set({ accountNo: e.target.value.replace(/\D/g, '') })} />
            <TextField label="IFSC" name="ifsc" required maxLength={11} error={errors.ifsc} value={form.ifsc} disabled={disabled} onChange={(e) => set({ ifsc: e.target.value.toUpperCase() })} placeholder="HDFC0001234" />
          </div>
        </Section>
      )}

      {show('agreement') && (
        <Section>
          <SectionTitle num={num()} title="Agreement Details" />
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            <TextField label="Agreement number" name="agreementNo" required error={errors.agreementNo} value={form.agreementNo} disabled={disabled} onChange={(e) => set({ agreementNo: e.target.value.toUpperCase() })} placeholder="AGR-2026-12345" />
            <TextField label="Agreement date" name="agreementDate" type="date" required error={errors.agreementDate} value={form.agreementDate} disabled={disabled} onChange={(e) => set({ agreementDate: e.target.value })} />
            <TextField label="Valid till" name="agreementValidTill" type="date" required error={errors.agreementValidTill} value={form.agreementValidTill} disabled={disabled} onChange={(e) => set({ agreementValidTill: e.target.value })} />
          </div>
        </Section>
      )}

      {show('kyc') && (
        <Section>
          <SectionTitle num={num()} title="KYC Documents" sub={form.entity ? `Checklist for ${form.entity}` : 'Select the entity type to see the required documents.'} />
          <div className="grid gap-4 sm:grid-cols-2">
            {docs.map((d) => (
              <div key={d}>
                <div className="mb-1.5 text-[11px] font-semibold text-ink">{d} *</div>
                <FileDrop entity="Franchise" purpose="franchise-registration" value={form.docs[d] ?? null} disabled={disabled} accept=".pdf,.jpg,.jpeg,.png" onChange={(f) => set({ docs: { ...form.docs, [d]: f } })} compact />
                {errors[`doc:${d}`] && <p className="mt-1 text-[11px] text-brand-red">{errors[`doc:${d}`]}</p>}
              </div>
            ))}
            {form.entity && (
              <div>
                <div className="mb-1.5 text-[11px] font-semibold text-ink">Other document (optional)</div>
                <FileDrop entity="Franchise" purpose="franchise-registration" value={form.docs['Other'] ?? null} disabled={disabled} accept=".pdf,.jpg,.jpeg,.png" onChange={(f) => set({ docs: { ...form.docs, Other: f } })} compact />
              </div>
            )}
          </div>
        </Section>
      )}

      {show('mapping') && (
        <Section>
          <SectionTitle num={num()} title="Mapping Details" sub={tier === 'Super Master' ? 'An SMF is mapped directly to Dexter India.' : tier === 'Master' ? 'An MF can work under an SMF or directly under the company (§3.1).' : 'An FR can work under an MF, directly under the company, or under a Team Leader (§1).'} />
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            <SelectField label="Reporting manager" name="reportingManager" required error={errors.reportingManager} options={MANAGERS.map((m) => m.name)} value={form.reportingManager} disabled={disabled} onChange={(e) => set({ reportingManager: e.target.value })} />
            <SelectField label="Assigned team" name="assignedTeam" required error={errors.assignedTeam} options={TEAMS} value={form.assignedTeam} disabled={disabled} onChange={(e) => set({ assignedTeam: e.target.value })} />
            <div className="hidden lg:block" />
            {parentLocked ? (
              <ReadOnlyField label="Parent" value={parentLabel ?? (form.parentKind ? PARENT_KIND_LABEL[form.parentKind] : '—')} hint="Change the parent from the Parent Mapping tab (approval needed)." />
            ) : (
              <PickField
                label="Parent type"
                name="parentKind"
                required
                error={errors.parentKind}
                options={PARENT_KINDS[tier].map((k) => ({ value: k, label: PARENT_KIND_LABEL[k] }))}
                value={form.parentKind}
                disabled={disabled || tier === 'Super Master'}
                onChange={(e) => set({ parentKind: e.target.value as ParentKind | '', parentId: '' })}
              />
            )}
            {!parentLocked && form.parentKind && form.parentKind !== 'Company' && (
              <PickField
                label={PARENT_KIND_LABEL[form.parentKind]}
                name="parentId"
                required
                error={errors.parentId}
                options={parentOpts}
                value={form.parentId}
                disabled={disabled}
                onChange={(e) => set({ parentId: e.target.value })}
                className="lg:col-span-2"
              />
            )}
          </div>
        </Section>
      )}
    </div>
  )
}

function Section({ children }: { children: ReactNode }) {
  return <section className="rounded-xl border border-slate-200 bg-white p-4 sm:p-5">{children}</section>
}
