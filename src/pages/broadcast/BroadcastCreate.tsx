import { useState } from 'react'
import { useNavigate } from 'react-router-dom'
import {
  Calendar,
  ChevronDown,
  Paperclip,
  Plus,
  Radio,
  Sparkles,
  X,
} from 'lucide-react'
import { addBroadcast } from '@/data/broadcasts'
import { toast } from '@/components/ui/Toast'
import { cn } from '@/lib/cn'

export default function BroadcastCreate() {
  const navigate = useNavigate()

  // Form Fields matching Image 3
  const [broadcastType, setBroadcastType] = useState('Policy Circular')
  const [priority, setPriority] = useState<'Critical' | 'Urgent' | 'Important' | 'Normal'>('Important')
  const [language, setLanguage] = useState('English + Hindi')
  const [subject, setSubject] = useState('New Cash Loading Policy - Effective 10 Nov 2026')
  const [message, setMessage] = useState(
`Dear Team,
Please note that revised cash loading guidelines will apply to all Cash Live sites from 10 Nov 2026. Cash loading must be confirmed in the ERP before 11:00 AM, and every mismatch must be reported in the same-day CBR.
Kindly acknowledge this notice after reading.

Regards, Operations Department`
  )
  const [attachment, setAttachment] = useState<{ name: string; size: string } | null>({
    name: 'Cash_Loading_Policy_v3.pdf',
    size: '1.2 MB',
  })
  const [publishSchedule, setPublishSchedule] = useState('Schedule - 05 Nov 2026, 10:30 AM')

  // Audience Groups matching Image 3
  const [audienceGroups, setAudienceGroups] = useState<string[]>([
    'Cash Live Franchisees (142)',
    'Operations (38)',
    'Field Team (96)',
    'Cash Loading Team (24)',
    'Managers & HODs (19)',
  ])

  // Delivery Channels
  const [channels, setChannels] = useState<{ inApp: boolean; email: boolean; whatsApp: boolean; sms: boolean }>({
    inApp: true,
    email: true,
    whatsApp: true,
    sms: false,
  })

  // AI Prompt State
  const [aiPrompt, setAiPrompt] = useState('Cash loading policy change for all cash live sites')
  const [isGenerating, setIsGenerating] = useState(false)
  const [previewOpen, setPreviewOpen] = useState(false)

  // Calculate recipients
  const totalRecipients = 319

  const removeAudienceGroup = (group: string) => {
    setAudienceGroups((prev) => prev.filter((g) => g !== group))
  }

  const addAudienceGroup = () => {
    const newGroup = prompt('Enter department or audience group (e.g. "Customer Support (15)"):')
    if (newGroup && newGroup.trim()) {
      setAudienceGroups((prev) => [...prev, newGroup.trim()])
      toast(`Added audience group "${newGroup.trim()}"`, 'info')
    }
  }

  const handleAiAction = (action: string) => {
    setIsGenerating(true)
    setTimeout(() => {
      setIsGenerating(false)
      if (action === 'generate') {
        setMessage(
`Attention Team & Franchisees,
Per RBI WLA compliance framework and Dexter Operations circular, updated cash loading SLAs are effective immediately for all active Cash Live sites.
1. Daily replenishment confirmation deadline: 11:00 AM IST.
2. Immediate CBR variance escalation protocol active.
3. Electronic acknowledgement mandatory within 24 hours.

Regards, Central Operations Command`
        )
        toast('Message generated by AI Assistant', 'success')
      } else if (action === 'improve') {
        setMessage((prev) => `${prev}\n\n[Note: Failure to adhere to cash confirmation cutoff will trigger automated SLA warning.]`)
        toast('Draft enhanced with clarity and compliance phrasing', 'info')
      } else if (action === 'translate') {
        setMessage((prev) => `${prev}\n\n--- हिंदी अनुवाद ---\nप्रिय टीम, कृपया ध्यान दें कि 10 नवंबर 2026 से सभी कैश लाइव साइटों पर संशोधित कैश लोडिंग दिशानिर्देश लागू होंगे। ईआरपी में सुबह 11:00 बजे से पहले पुष्टि आवश्यक है।`)
        toast('Hindi translation appended to message', 'info')
      } else if (action === 'summary') {
        setMessage(
`Summary:
- New Cash Loading Policy effective 10 Nov 2026.
- 11:00 AM ERP confirmation cutoff.
- Same-day CBR variance reporting mandatory.`
        )
        toast('Short bullet summary generated', 'info')
      } else if (action === 'subject') {
        setSubject('Urgent: Revised Cash Replenishment & CBR Verification SLA (Effective 10 Nov)')
        toast('Suggested high-read-rate subject applied', 'info')
      } else if (action === 'pdf') {
        toast('Summarised 12-page Cash Loading SOP into key operational highlights', 'info')
      }
    }, 600)
  }

  const handleSubmitForApproval = () => {
    if (!subject.trim() || !message.trim()) {
      toast('Please enter subject and message', 'info')
      return
    }

    addBroadcast({
      title: subject,
      subject,
      type: broadcastType,
      audience: audienceGroups[0]?.split(' ')[0] || 'Operations',
      audienceGroups,
      recipientsCount: totalRecipients,
      priority,
      language,
      message,
      attachment: attachment || undefined,
      publishType: 'Scheduled',
      scheduledFor: publishSchedule,
      status: 'Pending Approval',
      readPercentage: 0,
      channels: Object.entries(channels).filter(([_, v]) => v).map(([k]) => k === 'inApp' ? 'In-App' : k === 'whatsApp' ? 'WhatsApp' : k.toUpperCase()),
      ackRequired: true,
      approvalLevel: 'HOD',
      createdBy: 'Paras Dubey',
      submittedAt: 'Just now',
    })

    toast('Broadcast submitted for HOD approval queue', 'success')
    navigate('/work-management/broadcast/approval-queue')
  }

  const handleSaveDraft = () => {
    addBroadcast({
      title: subject || 'Untitled Broadcast',
      subject: subject || 'Untitled Broadcast',
      type: broadcastType,
      audience: audienceGroups[0]?.split(' ')[0] || 'Operations',
      audienceGroups,
      recipientsCount: totalRecipients,
      priority,
      language,
      message,
      publishType: 'Instant',
      status: 'Draft',
      readPercentage: 0,
      channels: ['In-App'],
      ackRequired: false,
      createdBy: 'Paras Dubey',
      submittedAt: 'Just now',
    })

    toast('Broadcast saved to Drafts', 'info')
    navigate('/work-management/broadcast/scheduled')
  }

  return (
    <div className="space-y-6 pb-16">
      {/* Header matching Image 3 */}
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div className="flex items-center gap-3">
          <div className="grid h-10 w-10 place-items-center rounded-xl bg-blue-100/70 text-[#0066FF]">
            <Radio size={20} className="text-[#0066FF]" />
          </div>
          <div>
            <h1 className="text-2xl font-bold tracking-tight text-[#0f172a]">Create New Broadcast</h1>
          </div>
        </div>

        <div className="flex items-center gap-2.5">
          <button
            type="button"
            onClick={handleSaveDraft}
            className="rounded-lg border border-slate-200 bg-white px-4 py-2 text-xs font-semibold text-slate-700 shadow-2xs hover:bg-slate-50 transition-all"
          >
            Save Draft
          </button>
          <button
            type="button"
            onClick={() => setPreviewOpen(true)}
            className="rounded-lg border border-slate-200 bg-white px-4 py-2 text-xs font-semibold text-slate-700 shadow-2xs hover:bg-slate-50 transition-all"
          >
            Preview
          </button>
          <button
            type="button"
            onClick={handleSubmitForApproval}
            className="flex items-center gap-1.5 rounded-lg bg-[#0066FF] hover:bg-blue-700 px-5 py-2 text-xs font-semibold text-white shadow-xs transition-all"
          >
            <span>Submit for Approval</span>
          </button>
        </div>
      </div>

      {/* Main Form Layout (2 Columns matching Image 3) */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left Column: Broadcast Details & Audience (approx 65% width) */}
        <div className="lg:col-span-8 space-y-6">
          {/* Card: Broadcast Details */}
          <div className="rounded-2xl border border-slate-200/90 bg-white p-5 sm:p-6 shadow-2xs space-y-5">
            <div className="flex items-center gap-2 border-b border-slate-100 pb-3">
              <span className="h-2.5 w-2.5 rounded-sm bg-[#0066FF]" />
              <h2 className="text-sm font-bold text-slate-900">Broadcast Details</h2>
            </div>

            {/* Row 1: Broadcast Type, Priority, Language */}
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
              <div>
                <label className="block text-[11px] font-bold text-slate-700 mb-1">
                  Broadcast Type <span className="text-red-500">*</span>
                </label>
                <div className="relative">
                  <select
                    value={broadcastType}
                    onChange={(e) => setBroadcastType(e.target.value)}
                    className="w-full h-9 px-3 pr-7 text-xs rounded-xl border border-slate-200 bg-white text-slate-800 outline-none focus:border-[#0066FF] appearance-none font-medium shadow-2xs"
                  >
                    <option value="Policy Circular">Policy Circular</option>
                    <option value="SOP Update">SOP Update</option>
                    <option value="Compliance Alert">Compliance Alert</option>
                    <option value="Festival Greeting">Festival Greeting</option>
                    <option value="System Maintenance">System Maintenance</option>
                    <option value="Scheme Launch">Scheme Launch</option>
                    <option value="Training Notice">Training Notice</option>
                  </select>
                  <ChevronDown size={14} className="pointer-events-none absolute right-2.5 top-1/2 -translate-y-1/2 text-slate-400" />
                </div>
              </div>

              <div>
                <label className="block text-[11px] font-bold text-slate-700 mb-1">
                  Priority <span className="text-red-500">*</span>
                </label>
                <div className="relative">
                  <select
                    value={priority}
                    onChange={(e) => setPriority(e.target.value as any)}
                    className="w-full h-9 px-3 pr-7 text-xs rounded-xl border border-slate-200 bg-white text-slate-800 outline-none focus:border-[#0066FF] appearance-none font-medium shadow-2xs"
                  >
                    <option value="Important">Important</option>
                    <option value="Critical">Critical</option>
                    <option value="Urgent">Urgent</option>
                    <option value="Normal">Normal</option>
                  </select>
                  <ChevronDown size={14} className="pointer-events-none absolute right-2.5 top-1/2 -translate-y-1/2 text-slate-400" />
                </div>
              </div>

              <div>
                <label className="block text-[11px] font-bold text-slate-700 mb-1">
                  Language <span className="text-red-500">*</span>
                </label>
                <div className="relative">
                  <select
                    value={language}
                    onChange={(e) => setLanguage(e.target.value)}
                    className="w-full h-9 px-3 pr-7 text-xs rounded-xl border border-slate-200 bg-white text-slate-800 outline-none focus:border-[#0066FF] appearance-none font-medium shadow-2xs"
                  >
                    <option value="English + Hindi">English + Hindi</option>
                    <option value="English">English</option>
                    <option value="Hindi">Hindi</option>
                    <option value="Multi-Lingual">Multi-Lingual (Regional)</option>
                  </select>
                  <ChevronDown size={14} className="pointer-events-none absolute right-2.5 top-1/2 -translate-y-1/2 text-slate-400" />
                </div>
              </div>
            </div>

            {/* Row 2: Subject */}
            <div>
              <label className="block text-[11px] font-bold text-slate-700 mb-1">
                Subject <span className="text-red-500">*</span>
              </label>
              <input
                type="text"
                value={subject}
                onChange={(e) => setSubject(e.target.value)}
                placeholder="e.g. New Cash Loading Policy - Effective 10 Nov 2026"
                className="w-full h-9 px-3 text-xs rounded-xl border border-slate-200 bg-white text-slate-900 outline-none focus:border-[#0066FF] font-semibold shadow-2xs"
              />
            </div>

            {/* Row 3: Message */}
            <div>
              <label className="block text-[11px] font-bold text-slate-700 mb-1">
                Message <span className="text-red-500">*</span>
              </label>
              <textarea
                rows={7}
                value={message}
                onChange={(e) => setMessage(e.target.value)}
                className="w-full p-3.5 text-xs rounded-xl border border-slate-200 bg-white text-slate-800 outline-none focus:border-[#0066FF] font-normal leading-relaxed shadow-2xs resize-y"
              />
            </div>

            {/* Row 4: Attachment & Publish Schedule */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 pt-1">
              {/* Attachment Box */}
              <div>
                <label className="block text-[11px] font-bold text-slate-700 mb-1">
                  Attachment
                </label>
                <div className="flex h-10 items-center justify-between rounded-xl border border-blue-200 bg-blue-50/50 px-3 text-xs shadow-2xs">
                  <div className="flex items-center gap-2 truncate">
                    <Paperclip size={14} className="text-[#0066FF] shrink-0" />
                    <span className="font-medium text-[#0066FF] truncate">
                      {attachment ? `${attachment.name} (${attachment.size})` : 'No file attached'}
                    </span>
                  </div>
                  {attachment ? (
                    <button
                      type="button"
                      onClick={() => setAttachment(null)}
                      className="text-slate-400 hover:text-red-600 p-1"
                    >
                      <X size={13} />
                    </button>
                  ) : (
                    <button
                      type="button"
                      onClick={() => setAttachment({ name: 'Cash_Loading_Policy_v3.pdf', size: '1.2 MB' })}
                      className="text-xs font-semibold text-[#0066FF] hover:underline"
                    >
                      Browse
                    </button>
                  )}
                </div>
              </div>

              {/* Publish Scheduler */}
              <div>
                <label className="block text-[11px] font-bold text-slate-700 mb-1">
                  Publish
                </label>
                <div className="relative">
                  <input
                    type="text"
                    value={publishSchedule}
                    onChange={(e) => setPublishSchedule(e.target.value)}
                    placeholder="Schedule - 05 Nov 2026, 10:30 AM"
                    className="w-full h-10 px-3 pr-8 text-xs rounded-xl border border-slate-200 bg-white text-slate-800 outline-none focus:border-[#0066FF] font-medium shadow-2xs"
                  />
                  <Calendar size={14} className="pointer-events-none absolute right-3 top-1/2 -translate-y-1/2 text-slate-400" />
                </div>
              </div>
            </div>
          </div>

          {/* Card: Audience matching Image 3 */}
          <div className="rounded-2xl border border-slate-200/90 bg-white p-5 sm:p-6 shadow-2xs space-y-4">
            <div className="flex items-center justify-between border-b border-slate-100 pb-3">
              <div className="flex items-center gap-2">
                <span className="h-2.5 w-2.5 rounded-sm bg-[#0066FF]" />
                <h2 className="text-sm font-bold text-slate-900">Audience</h2>
              </div>
              <span className="text-xs font-bold text-[#0066FF]">
                Total recipients: {totalRecipients}
              </span>
            </div>

            {/* Audience Chips */}
            <div className="flex flex-wrap items-center gap-2 pt-1">
              {audienceGroups.map((group) => (
                <span
                  key={group}
                  className="inline-flex items-center gap-1.5 rounded-full border border-blue-200 bg-blue-50/70 px-3 py-1 text-xs font-medium text-[#0066FF] shadow-2xs"
                >
                  <span>{group}</span>
                  <button
                    type="button"
                    onClick={() => removeAudienceGroup(group)}
                    className="grid h-4 w-4 place-items-center rounded-full hover:bg-blue-200/80 text-blue-700"
                  >
                    <X size={11} />
                  </button>
                </span>
              ))}

              <button
                type="button"
                onClick={addAudienceGroup}
                className="inline-flex items-center gap-1 rounded-full border border-dashed border-slate-300 bg-slate-50/60 px-3 py-1 text-xs font-semibold text-slate-600 hover:border-[#0066FF] hover:bg-blue-50 hover:text-[#0066FF] transition-all"
              >
                <Plus size={12} />
                <span>+ Add Audience</span>
              </button>
            </div>
          </div>
        </div>

        {/* Right Column: AI Assistant & Delivery Channels (approx 35% width) */}
        <div className="lg:col-span-4 space-y-6">
          {/* Card 1: AI Broadcast Assistant matching Image 3 */}
          <div className="rounded-2xl border border-purple-200 bg-purple-50/30 p-5 shadow-2xs space-y-3.5">
            <div className="flex items-center gap-2 text-purple-900">
              <Sparkles size={16} className="text-purple-600" />
              <h3 className="text-xs font-bold uppercase tracking-wider text-purple-900">
                AI Broadcast Assistant
              </h3>
            </div>

            <div>
              <label className="block text-[11px] font-medium text-slate-600 mb-1">
                Describe what you want to announce
              </label>
              <textarea
                rows={2}
                value={aiPrompt}
                onChange={(e) => setAiPrompt(e.target.value)}
                placeholder="e.g. Cash loading policy change for all cash live sites"
                className="w-full p-2.5 text-xs rounded-xl border border-purple-200 bg-white text-slate-800 outline-none focus:border-purple-500 shadow-2xs font-medium resize-none"
              />
            </div>

            {/* Action Buttons Grid matching Image 3 */}
            <div className="grid grid-cols-2 gap-2 pt-1">
              <button
                type="button"
                onClick={() => handleAiAction('generate')}
                disabled={isGenerating}
                className="py-1.5 px-2.5 rounded-lg border border-purple-300 bg-purple-100/70 hover:bg-purple-200/70 text-purple-900 text-xs font-semibold transition-all shadow-2xs truncate"
              >
                {isGenerating ? 'Generating...' : 'Generate Message'}
              </button>
              <button
                type="button"
                onClick={() => handleAiAction('improve')}
                className="py-1.5 px-2.5 rounded-lg border border-purple-200 bg-white hover:bg-purple-50 text-purple-800 text-xs font-semibold transition-all shadow-2xs truncate"
              >
                Improve
              </button>
              <button
                type="button"
                onClick={() => handleAiAction('translate')}
                className="py-1.5 px-2.5 rounded-lg border border-purple-200 bg-white hover:bg-purple-50 text-slate-700 text-xs font-semibold transition-all shadow-2xs truncate"
              >
                Translate to Hindi
              </button>
              <button
                type="button"
                onClick={() => handleAiAction('summary')}
                className="py-1.5 px-2.5 rounded-lg border border-purple-200 bg-white hover:bg-purple-50 text-slate-700 text-xs font-semibold transition-all shadow-2xs truncate"
              >
                Short Summary
              </button>
              <button
                type="button"
                onClick={() => handleAiAction('subject')}
                className="py-1.5 px-2.5 rounded-lg border border-purple-200 bg-white hover:bg-purple-50 text-slate-700 text-xs font-semibold transition-all shadow-2xs truncate"
              >
                Suggest Subject
              </button>
              <button
                type="button"
                onClick={() => handleAiAction('pdf')}
                className="py-1.5 px-2.5 rounded-lg border border-purple-200 bg-white hover:bg-purple-50 text-slate-700 text-xs font-semibold transition-all shadow-2xs truncate"
              >
                Summarise PDF
              </button>
            </div>
          </div>

          {/* Card 2: AI Suggestions matching Image 3 */}
          <div className="rounded-2xl border border-slate-200/90 bg-white p-5 shadow-2xs space-y-3">
            <div className="flex items-center gap-2">
              <span className="h-2.5 w-2.5 rounded-sm bg-[#0066FF]" />
              <h3 className="text-xs font-bold text-slate-900">AI Suggestions</h3>
            </div>

            <div className="space-y-2 text-xs">
              <div className="flex items-center justify-between py-1">
                <span className="text-slate-600">
                  Priority: <strong className="text-blue-700 bg-blue-50 px-2 py-0.5 rounded ml-1">Important</strong>
                </span>
                <button
                  type="button"
                  onClick={() => {
                    setPriority('Important')
                    toast('Priority set to Important', 'info')
                  }}
                  className="text-xs font-bold text-[#0066FF] hover:underline"
                >
                  Apply
                </button>
              </div>

              <div className="flex items-center justify-between py-1">
                <span className="text-slate-600">
                  Best time: <strong className="text-slate-800 ml-1">10:30 AM</strong>
                </span>
                <button
                  type="button"
                  onClick={() => {
                    setPublishSchedule('Schedule - 05 Nov 2026, 10:30 AM')
                    toast('Best delivery time 10:30 AM applied', 'info')
                  }}
                  className="text-xs font-bold text-[#0066FF] hover:underline"
                >
                  Apply
                </button>
              </div>

              <div className="flex items-center justify-between py-1">
                <span className="text-slate-600">
                  Audience: <strong className="text-slate-800 ml-1">5 groups, 319 users</strong>
                </span>
                <span className="text-xs font-bold text-emerald-600">Applied</span>
              </div>

              <div className="flex items-center justify-between py-1 pt-2 border-t border-slate-100">
                <span className="text-slate-600">Duplicate check:</span>
                <span className="rounded-full bg-emerald-50 px-2.5 py-0.5 text-[11px] font-bold text-emerald-700 border border-emerald-200">
                  No similar broadcast
                </span>
              </div>

              <div className="flex items-center justify-between py-1">
                <span className="text-slate-600">Sensitive content:</span>
                <span className="rounded-full bg-emerald-50 px-2.5 py-0.5 text-[11px] font-bold text-emerald-700 border border-emerald-200">
                  None found
                </span>
              </div>
            </div>
          </div>

          {/* Card 3: Delivery Channels matching Image 3 */}
          <div className="rounded-2xl border border-slate-200/90 bg-white p-5 shadow-2xs space-y-3">
            <div className="flex items-center gap-2">
              <span className="h-2.5 w-2.5 rounded-sm bg-[#0066FF]" />
              <h3 className="text-xs font-bold text-slate-900">Delivery Channels</h3>
            </div>

            <div className="flex flex-wrap gap-2 pt-1">
              {[
                { key: 'inApp' as const, label: 'In-App ✓' },
                { key: 'email' as const, label: 'Email ✓' },
                { key: 'whatsApp' as const, label: 'WhatsApp ✓' },
                { key: 'sms' as const, label: 'SMS' },
              ].map((ch) => {
                const active = channels[ch.key]
                return (
                  <button
                    key={ch.key}
                    type="button"
                    onClick={() => setChannels((c) => ({ ...c, [ch.key]: !c[ch.key] }))}
                    className={cn(
                      'rounded-lg px-3 py-1.5 text-xs font-semibold transition-all border shadow-2xs',
                      active
                        ? 'border-emerald-300 bg-emerald-50 text-emerald-800'
                        : 'border-slate-200 bg-slate-50 text-slate-500'
                    )}
                  >
                    {ch.label}
                  </button>
                )
              })}
            </div>

            <p className="text-[11.5px] font-medium text-slate-500 pt-1">
              Acknowledgement required:{' '}
              <strong className="text-slate-800">Yes</strong> · Approval:{' '}
              <strong className="text-slate-800">HOD</strong>
            </p>
          </div>
        </div>
      </div>

      {/* Live Preview Modal */}
      {previewOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 backdrop-blur-xs p-4">
          <div className="w-full max-w-xl rounded-2xl bg-white p-6 shadow-2xl border border-slate-200 space-y-4">
            <div className="flex items-start justify-between border-b border-slate-100 pb-3">
              <div>
                <span className="rounded bg-blue-100 px-2 py-0.5 text-[10px] font-bold text-[#0066FF] uppercase">
                  {broadcastType}
                </span>
                <h2 className="text-lg font-bold text-slate-900 mt-1">{subject}</h2>
              </div>
              <button
                type="button"
                onClick={() => setPreviewOpen(false)}
                className="text-slate-400 hover:text-slate-700"
              >
                ✕
              </button>
            </div>

            <div className="flex flex-wrap gap-2 text-xs">
              <span className="rounded-full bg-blue-50 px-2.5 py-0.5 text-blue-700 font-semibold border border-blue-200">
                Priority: {priority}
              </span>
              <span className="rounded-full bg-slate-100 px-2.5 py-0.5 text-slate-700 font-medium">
                {audienceGroups.length} groups · {totalRecipients} recipients
              </span>
              <span className="rounded-full bg-emerald-50 px-2.5 py-0.5 text-emerald-700 font-medium border border-emerald-200">
                Ack Required
              </span>
            </div>

            <div className="rounded-xl bg-slate-50 p-4 border border-slate-100 text-xs text-slate-800 leading-relaxed whitespace-pre-line font-normal">
              {message}
            </div>

            {attachment && (
              <div className="flex items-center gap-2 rounded-lg border border-slate-200 bg-white p-2.5 text-xs text-slate-700">
                <Paperclip size={14} className="text-[#0066FF]" />
                <span className="font-medium">{attachment.name}</span>
                <span className="text-slate-400">({attachment.size})</span>
              </div>
            )}

            <div className="flex items-center justify-between text-xs text-slate-500 pt-3 border-t border-slate-100">
              <span>{publishSchedule}</span>
              <button
                type="button"
                onClick={() => setPreviewOpen(false)}
                className="rounded-lg bg-[#0066FF] px-4 py-1.5 text-xs font-semibold text-white"
              >
                Close Preview
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}
