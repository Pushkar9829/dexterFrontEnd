import { useMemo, useState } from 'react'
import { BellRing, CheckCheck, Clock, Mail, MailOpen, Save } from 'lucide-react'
import { Badge } from '@/components/ui/Badge'
import { toast } from '@/components/ui/Toast'
import { downloadCsv } from '@/lib/export'
import { cn } from '@/lib/cn'
import { can, useRole } from '@/lib/rbac'
import { WF_MODULES, logAudit, scheduleStore, useSchedules, useWorkflow, useWorkflowLoad, wfApi, wfStore, type NotifySchedule } from '@/data/workflow'
import { apiEnabled } from '@/lib/api'
import { BTN_PRIMARY, BTN_SECONDARY, EmptyRow, FilterCard, FilterSelect, PageHead, Stat, TD, THead, TROW, TableCard, Tabs, WfCrumbs } from './ui'
import { fmtDT, usePaged } from './helpers'

const TABS = ['Notification Centre', 'Schedules'] as const
type Tab = (typeof TABS)[number]

export default function Notifications() {
  const [tab, setTab] = useState<Tab>('Notification Centre')
  return (
    <div className="space-y-5 pb-16 max-w-[1440px]">
      <WfCrumbs trail={[{ label: 'Notifications' }]} />
      <PageHead title="Notifications" sub="In-app / mobile alerts generated by the workflow engine, and the reminder schedules used by Operations (e.g. chargeback follow-ups)." />
      <Tabs tabs={TABS} value={tab} onChange={setTab} />
      {tab === 'Notification Centre' ? <Centre /> : <Schedules />}
    </div>
  )
}

const COLS = ['', 'Date / Time', 'Recipient', 'Channel', 'Module', 'Record', 'Message', 'Action']

function Centre() {
  const { notices } = useWorkflow()
  useWorkflowLoad(['notices']) // API mode: own notifications (GET /notifications)
  const [q, setQ] = useState('')
  const [read, setRead] = useState('all')
  const [mod, setMod] = useState('all')
  const [to, setTo] = useState('all')
  const recipients = useMemo(() => [...new Set(notices.map((n) => n.to))].sort(), [notices])
  const rows = useMemo(() => {
    const s = q.trim().toLowerCase()
    return notices.filter(
      (n) =>
        (read === 'all' || (read === 'Unread' ? !n.read : n.read)) &&
        (mod === 'all' || n.module === mod) &&
        (to === 'all' || n.to === to) &&
        (!s || [n.text, n.refId, n.to].some((v) => v.toLowerCase().includes(s))),
    )
  }, [notices, q, read, mod, to])
  const pg = usePaged(rows, `${q}|${read}|${mod}|${to}`)
  const unread = notices.filter((n) => !n.read).length

  const setReadFlag = (ids: Set<string>, flag: boolean) => {
    if (apiEnabled && flag) void wfApi.markNoticesRead([...ids].filter((id) => notices.some((n) => n.id === id && !n.read)))
    return setReadFlagLocal(ids, flag)
  }
  const setReadFlagLocal = (ids: Set<string>, flag: boolean) => wfStore.set((s) => ({ ...s, notices: s.notices.map((n) => (ids.has(n.id) ? { ...n, read: flag } : n)) }))
  const markAll = () => {
    const ids = new Set(rows.filter((n) => !n.read).map((n) => n.id))
    if (!ids.size) {
      toast('Nothing unread in the current view.', 'info')
      return
    }
    setReadFlag(ids, true)
    toast(`${ids.size} notification(s) marked as read.`)
  }

  return (
    <>
      <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
        <Stat label="Notifications" value={notices.length} />
        <Stat label="Unread" value={unread} tone="text-amber-600" />
        <Stat label="Read" value={notices.length - unread} tone="text-emerald-600" />
        <Stat label="Recipients" value={recipients.length} tone="text-[#0066FF]" />
      </div>
      <FilterCard
        search={q}
        onSearch={setQ}
        placeholder="Message, record, recipient…"
        cols={5}
        onReset={() => {
          setQ('')
          setRead('all')
          setMod('all')
          setTo('all')
        }}
        onDownload={() => downloadCsv('notifications', ['At', 'Recipient', 'Channel', 'Module', 'Record', 'Message', 'Read'], rows.map((n) => [fmtDT(n.at), n.to, n.channel, n.module, n.refId, n.text, n.read ? 'Read' : 'Unread']))}
      >
        <FilterSelect label="Read status" value={read} onChange={setRead} options={['Unread', 'Read']} all="All" />
        <FilterSelect label="Module" value={mod} onChange={setMod} options={WF_MODULES} all="All modules" />
        <FilterSelect label="Recipient" value={to} onChange={setTo} options={recipients} all="All recipients" />
      </FilterCard>
      <TableCard
        title="Notification centre"
        total={rows.length}
        page={pg.page}
        pageSize={pg.pageSize}
        onPage={pg.setPage}
        onPageSize={pg.setPageSize}
        noun="notifications"
        minWidth={1100}
        action={<button type="button" className={BTN_SECONDARY} onClick={markAll}><CheckCheck size={14} /> Mark view as read</button>}
      >
        <THead cols={COLS} />
        <tbody>
          {pg.slice.length === 0 && <EmptyRow cols={COLS.length} text={notices.length ? 'No notifications match the filters.' : 'No notifications yet.'} />}
          {pg.slice.map((n) => (
            <tr key={n.id} className={cn(TROW, !n.read && 'bg-blue-50/40 font-semibold')}>
              <td className={TD}><span className={cn('inline-block h-2 w-2 rounded-full', n.read ? 'bg-slate-300' : 'bg-[#0066FF]')} aria-label={n.read ? 'Read' : 'Unread'} /></td>
              <td className={TD}>{fmtDT(n.at)}</td>
              <td className={TD}>{n.to}</td>
              <td className={TD}><Badge tone="navy" dot={false}>{n.channel}</Badge></td>
              <td className={TD}>{n.module}</td>
              <td className={TD}>{n.refId}</td>
              <td className={`${TD} max-w-[420px] truncate`} title={n.text}>{n.text}</td>
              <td className={TD}>
                <button type="button" className="inline-flex items-center gap-1 font-semibold text-[#0066FF] hover:underline" onClick={() => setReadFlag(new Set([n.id]), !n.read)}>
                  {n.read ? <><Mail size={13} /> Mark unread</> : <><MailOpen size={13} /> Mark read</>}
                </button>
              </td>
            </tr>
          ))}
        </tbody>
      </TableCard>
    </>
  )
}

// ── Schedules ────────────────────────────────────────────────────────────
type Draft = { perDay: string; times: string[] }
const TIME_RE = /^([01]\d|2[0-3]):[0-5]\d$/

function Schedules() {
  const canEdit = can('Edit', useRole())
  const schedules = useSchedules()
  return (
    <div className="grid gap-5 lg:grid-cols-2">
      {schedules.map((s) => (
        <ScheduleCard key={s.key} s={s} canEdit={canEdit} />
      ))}
      <div className="lg:col-span-2 flex justify-end">
        <button type="button" className={BTN_SECONDARY} onClick={() => downloadCsv('notification-schedules', ['Key', 'Schedule', 'Per day', 'Times'], schedules.map((s) => [s.key, s.label, String(s.perDay), s.times.join(' / ')]))}>
          Download schedules
        </button>
      </div>
    </div>
  )
}

function ScheduleCard({ s, canEdit }: { s: NotifySchedule; canEdit: boolean }) {
  const [d, setD] = useState<Draft>({ perDay: String(s.perDay), times: s.times })
  const [err, setErr] = useState<{ perDay?: string; times?: string }>({})
  const setPerDay = (v: string) => {
    const n = Number(v)
    setD((p) => {
      if (!Number.isInteger(n) || n < 1 || n > 12) return { ...p, perDay: v }
      const times = p.times.slice(0, n)
      while (times.length < n) times.push('')
      return { perDay: v, times }
    })
    setErr({})
  }
  const save = () => {
    const n = Number(d.perDay)
    const e: typeof err = {}
    if (!Number.isInteger(n) || n < 1 || n > 12) e.perDay = 'Enter 1–12 reminders per day.'
    else if (d.times.length !== n || d.times.some((t) => !TIME_RE.test(t))) e.times = `Enter ${n} valid time(s) (HH:MM).`
    else if (new Set(d.times).size !== d.times.length) e.times = 'Times must be different.'
    setErr(e)
    if (Object.keys(e).length) return
    const times = [...d.times].sort()
    scheduleStore.set((list) => list.map((x) => (x.key === s.key ? { ...x, perDay: n, times } : x)))
    logAudit('Notification Schedule', s.key, 'Schedule updated', `${s.perDay}/day [${s.times.join(', ')}] → ${n}/day [${times.join(', ')}]`)
    setD({ perDay: String(n), times })
    toast('Schedule saved.')
  }
  const dirty = d.perDay !== String(s.perDay) || d.times.join() !== s.times.join()
  return (
    <div className="rounded-xl border border-slate-200 bg-white p-5 shadow-sm">
      <div className="mb-4 flex items-start gap-3">
        <span className="grid h-9 w-9 shrink-0 place-items-center rounded-lg bg-[#0066FF] text-white"><BellRing size={17} /></span>
        <div>
          <div className="text-[14px] font-bold text-slate-900">{s.label}</div>
          <div className="text-[12px] text-slate-500">Currently {s.perDay}× per day at {s.times.join(', ')}</div>
        </div>
      </div>
      <fieldset disabled={!canEdit} className="space-y-3">
        <div>
          <label className="mb-1.5 block text-[11px] font-semibold text-ink" htmlFor={`pd-${s.key}`}>Reminders per day *</label>
          <input id={`pd-${s.key}`} type="number" min={1} max={12} value={d.perDay} onChange={(e) => setPerDay(e.target.value)} className={cn('h-9 w-[120px] rounded-md border px-2 text-[12.5px] outline-none focus:border-[#0066FF]', err.perDay ? 'border-brand-red' : 'border-slate-200')} />
          {err.perDay && <p className="mt-1 text-[11px] text-brand-red">{err.perDay}</p>}
        </div>
        <div>
          <div className="mb-1.5 text-[11px] font-semibold text-ink">Times *</div>
          <div className="flex flex-wrap gap-2">
            {d.times.map((t, i) => (
              <label key={`slot-${i}`} className="flex items-center gap-1.5 rounded-md border border-slate-200 px-2 py-1 text-[12px]">
                <Clock size={13} className="text-slate-400" />
                <input type="time" aria-label={`Time ${i + 1}`} value={t} onChange={(e) => { const v = e.target.value; setD((p) => ({ ...p, times: p.times.map((x, j) => (j === i ? v : x)) })); setErr({}) }} className="outline-none" />
              </label>
            ))}
          </div>
          {err.times && <p className="mt-1 text-[11px] text-brand-red">{err.times}</p>}
        </div>
      </fieldset>
      {canEdit && (
        <div className="mt-4 flex justify-end gap-2">
          <button type="button" className={BTN_SECONDARY} disabled={!dirty} onClick={() => { setD({ perDay: String(s.perDay), times: s.times }); setErr({}) }}>Undo</button>
          <button type="button" className={BTN_PRIMARY} disabled={!dirty} onClick={save}><Save size={14} /> Save</button>
        </div>
      )}
    </div>
  )
}
